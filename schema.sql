create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  site text default '',
  name text default '',
  phone text default '',
  date text default '',
  time text default '',
  status text not null default 'pending',
  notes jsonb not null default '{"before":"","after":"","contract":""}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.reservations enable row level security;
drop policy if exists "own_all" on public.reservations;
create policy "own_all" on public.reservations
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create index if not exists reservations_user_date on public.reservations (user_id, date);
